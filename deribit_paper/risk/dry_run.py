"""Global dry-run flag — the master safety switch.

When ``dry_run == True``, every code path that would place an order,
cancel an order, or otherwise mutate the exchange must honour the flag
and instead log what it *would* have done.  This is the single most
important safety mechanism in the entire paper-trading module: it
defaults to True and can only be disabled via the explicit
``--live`` CLI flag with passphrase confirmation.

Design:

- Process-global singleton (``DryRunState``) so every module sees the
  same flag without threading it through constructors.
- ``set_dry_run(False)`` requires a ``confirmation_token`` that is
  generated inside the CLI from a user-typed passphrase.  This
  prevents accidentally flipping the flag via a stray config load.
- Getting the flag via ``get_dry_run()`` is a cheap, lock-free read.

Usage in a production path (e.g., order manager)::

    from deribit_paper.risk.dry_run import get_dry_run

    async def place_order(self, ...):
        if get_dry_run():
            logger.info("DRY_RUN place_order %s", params)
            return STUB_FILL
        return await self._rest.place_order(...)
"""

from __future__ import annotations

import logging
import threading

logger = logging.getLogger(__name__)


# The module-level default — MUST be True.  The CLI is the only
# place that flips this, and only after explicit confirmation.
DRY_RUN_DEFAULT: bool = True


class DryRunState:
    """Singleton holding the global dry-run flag.

    Using a class instead of a bare ``bool`` makes it harder to
    accidentally rebind the flag (``dry_run = False`` in another module
    would only shadow the import; calling ``set_dry_run(False, ...)``
    requires a passphrase).
    """

    _instance: "DryRunState | None" = None
    _lock = threading.Lock()

    def __new__(cls) -> "DryRunState":
        with cls._lock:
            if cls._instance is None:
                cls._instance = super().__new__(cls)
                cls._instance._dry_run = DRY_RUN_DEFAULT
                cls._instance._armed = False
            return cls._instance

    @property
    def dry_run(self) -> bool:
        return self._dry_run  # type: ignore[return-value]

    def disable(self, *, confirmation_token: str) -> None:
        """Disable dry-run mode.

        Requires a non-empty ``confirmation_token`` that the CLI
        generates after the user has typed the confirmation passphrase.
        Any caller passing an empty or default token is rejected.
        """
        if not confirmation_token or confirmation_token == "default":
            raise RuntimeError(
                "disable() requires a valid confirmation_token generated "
                "by the CLI passphrase flow — refusing to flip DRY_RUN",
            )
        if self._dry_run:
            logger.warning(
                "DRY_RUN DISABLED — live orders will now be placed on Deribit",
            )
        self._dry_run = False
        self._armed = True

    def enable(self) -> None:
        """Re-enable dry-run mode (safe to call without a token)."""
        if not self._dry_run:
            logger.warning("DRY_RUN RE-ENABLED — no more live orders")
        self._dry_run = True
        self._armed = False

    def reset(self) -> None:
        """Reset to default (dry-run = True).

        Intended for tests.  Production code should never call this.
        """
        self._dry_run = DRY_RUN_DEFAULT
        self._armed = False


def get_dry_run() -> bool:
    """Return the current dry-run flag — cheap, lock-free read."""
    return DryRunState().dry_run


def set_dry_run(value: bool, *, confirmation_token: str = "default") -> None:
    """Set the dry-run flag.

    Setting to ``True`` is always allowed; setting to ``False`` requires
    a valid ``confirmation_token`` generated by the CLI passphrase flow.
    """
    state = DryRunState()
    if value:
        state.enable()
    else:
        state.disable(confirmation_token=confirmation_token)
